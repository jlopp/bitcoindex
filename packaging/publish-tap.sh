#!/usr/bin/env bash
# Publish a rendered Homebrew formula into the tap repository.
#
#   packaging/publish-tap.sh <formula.rb> <version>
#
# Environment:
#   TAP_REPO    owner/name of the tap repo (default: jlopp/homebrew-tap)
#   TAP_BRANCH  branch to push (default: main)
#   TAP_TOKEN   token with contents:write on the tap repo (required)
#
# The tap is an ordinary git repository holding one formula per file under
# Formula/. This clones it, drops in Formula/bitcoindex.rb, and pushes a commit
# only when the content actually changed, so re-running a release is a no-op
# rather than an empty commit.
#
# The formula itself is generated by packaging/update-formula.sh from a
# release's SHA256SUMS; this script only moves the finished file into the tap.
set -euo pipefail

formula="${1:?usage: publish-tap.sh <formula.rb> <version>}"
version="${2:?usage: publish-tap.sh <formula.rb> <version>}"

tap_repo="${TAP_REPO:-jlopp/homebrew-tap}"
tap_branch="${TAP_BRANCH:-main}"
token="${TAP_TOKEN:?publish-tap: TAP_TOKEN is required (contents:write on $tap_repo)}"

[ -f "$formula" ] || { echo "publish-tap: no such formula: $formula" >&2; exit 1; }

# Guard against pushing an unrendered template: a formula still carrying @@
# placeholders would install nothing and fail with a confusing sha256 error.
if grep -q '@@' "$formula"; then
    echo "publish-tap: $formula still contains @@ placeholders; render it first" >&2
    exit 1
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# `x-access-token` is the username GitHub accepts when the password is a PAT.
remote="https://x-access-token:${token}@github.com/${tap_repo}.git"

if ! git clone --depth 1 --branch "$tap_branch" "$remote" "$work/tap" 2>/dev/null; then
    {
        echo "publish-tap: could not clone $tap_repo@$tap_branch."
        echo "  Create the repository first (doc/INSTALL.md, Homebrew section) and"
        echo "  confirm TAP_TOKEN has contents:write on it."
    } >&2
    exit 1
fi

mkdir -p "$work/tap/Formula"
cp "$formula" "$work/tap/Formula/bitcoindex.rb"

cd "$work/tap" || exit 1
# `git status --porcelain` (not `git diff`) so a brand-new file is detected too.
if [ -z "$(git status --porcelain -- Formula/bitcoindex.rb)" ]; then
    echo "publish-tap: Formula/bitcoindex.rb already at $version; nothing to do"
    exit 0
fi

git config user.name "bitcoindex release bot"
git config user.email "jlopp@users.noreply.github.com"
git add Formula/bitcoindex.rb
git commit -m "bitcoindex $version"
git push origin "$tap_branch"
echo "publish-tap: pushed bitcoindex $version to $tap_repo ($tap_branch)"
